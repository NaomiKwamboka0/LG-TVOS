const char *tr(ft_lang lang, ft_str id)
{
    const char *s;
    if (id >= STR_COUNT)
        return "?";
    if (lang >= LANG_COUNT)
        lang = LANG_EN;
    s = TABLE[id][lang];
    return s ? s : TABLE[id][LANG_EN];
}

const char *lang_name(ft_lang lang)
{
    return lang == LANG_SW ? "Kiswahili" : "English";
}
