#!/usr/bin/env python3
"""Convert Spleen BDF fonts (ASCII 32-126) into ui/font_data.c.

Usage: python3 tools/bdf2c.py assets/fonts/spleen/spleen-12x24.bdf ... > ui/font_data.c
Output is deterministic so the generated file can be checked in and diffed.
"""
import os
import sys

FIRST, LAST = 32, 126


def parse(path):
    glyphs, width, height = {}, None, None
    enc, bitmap, in_bitmap = None, [], False
    with open(path, encoding="ascii") as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            key = parts[0]
            if key == "FONTBOUNDINGBOX":
                width, height = int(parts[1]), int(parts[2])
            elif key == "ENCODING":
                enc = int(parts[1])
            elif key == "BBX":
                if (int(parts[1]), int(parts[2])) != (width, height) or parts[3] != "0":
                    raise SystemExit(f"{path}: non full-cell glyph {enc}; converter needs updating")
            elif key == "BITMAP":
                in_bitmap, bitmap = True, []
            elif key == "ENDCHAR":
                if enc is not None and FIRST <= enc <= LAST:
                    if len(bitmap) != height:
                        raise SystemExit(f"{path}: glyph {enc} has {len(bitmap)} rows")
                    glyphs[enc] = bitmap
                in_bitmap, enc = False, None
            elif in_bitmap:
                bitmap.append(bytes.fromhex(key))
    return width, height, glyphs


def main(paths):
    out = ["/* Generated by tools/bdf2c.py from Spleen 2.1.0 (BSD-2-Clause, see",
           " * assets/fonts/spleen/LICENSE). Do not edit by hand. */",
           '#include "font.h"', ""]
    for path in paths:
        w, h, glyphs = parse(path)
        name = f"font_{w}x{h}"
        row_bytes = (w + 7) // 8
        out.append(f"static const uint8_t {name}_bits[] = {{")
        for code in range(FIRST, LAST + 1):
            rows = glyphs.get(code, glyphs[ord("?")])
            data = b"".join(r.ljust(row_bytes, b"\0")[:row_bytes] for r in rows)
            label = chr(code) if chr(code) not in "\\*/" else " "
            out.append(f"    /* {code:3d} '{label}' */ " + ",".join(f"0x{b:02x}" for b in data) + ",")
        out.append("};")
        out.append(f"const ft_font {name} = {{{w}, {h}, {FIRST}, {LAST - FIRST + 1}, {row_bytes}, {name}_bits}};")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    main(sys.argv[1:])
